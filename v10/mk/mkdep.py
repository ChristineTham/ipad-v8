# The subset that MAKES a Tenth Edition filesystem, ported to run on the
# Eighth Edition host.  Built from V10 source and nothing else: V8 has files
# of the same names -- mkbitfs.c, mkfs.c -- and they are eight years apart,
# so using V8's would be assuming the on-disk format never changed rather
# than reading V10's own answer to it.
#
# `mkbitfs' is the one that matters.  seki's root is `ra 0100', and
# BITFS(dev) = ((dev) & 64), so its root filesystem is the BITMAPPED variant:
# 4096-byte blocks, and free space held in S_bfree[BITMAP] rather than in the
# S_free[] list.  mkfs writes only the free-list form -- it is a Berkeley 4.2
# file that uses BSIZE(0) throughout -- so mkfs alone cannot make a
# filesystem seki can mount.  mkbitfs can: it opens with
#
#	#define ISBIT 0100    /* this is a bitmapped filesystem -- fake out macros */
#	#define ICOUNT INOPB(ISBIT)
#	#define BCOUNT BSIZE(ISBIT)
#
# and sets s_valid = 1.  It checks BITFS(st_rdev) on its target, so the raw
# device node it is pointed at must carry bit 6 in its minor number.
# NAMED v10<tool>, AND THAT IS A SAFETY PROPERTY, NOT A CONVENTION.
#
# These run on the EIGHTH Edition host, beside V8's own mkfs, mknod, dd and
# cpio.  A V10 tool that answered to `mkfs' on that machine would be one
# PATH accident away from being the one a build reached for, and the failure
# would be silent: V10's mkfs writes a superblock V8's kernel reads
# differently, so the damage would appear later, somewhere else, as a
# corrupt filesystem.
#
# The tape shows how bad this gets left to convention.  V10's own
# cmd/ccom/vax/makefile carries
#
#	install:
#		cp /lib/ccom comp.sv
#		cp comp /lib/ccom
#
# -- it overwrites the compiler you are compiling with, in `/', on the host.
# Nothing generated here can do that (every destination goes through
# $(DESTDIR) or $(TOOLDIR), asserted below), but the names make the
# separation visible rather than merely true.
#
# Files that go INTO the V10 image keep their real names: `init' has to be
# /etc/init there.  The prefix is only for tools executed on the host.
FSTOOL_SRC = ["mkbitfs", "mknod", "dd", "cpio"]
FSTOOLS = ["v10" + n for n in FSTOOL_SRC]

# A machine you can STOP.  Deliberately not folded into BOOTPATH, whose
# comment is about what a boot needs and would stop being true.
#
# The first golden shipped without either and that was a real defect, because
# V10's shutdown is not V8's.  lsys/md/machdep.c, entire:
#
#	boot(howto)  { if (howto&RB_HALT) death(); reboot(1); }
#	death()      { splx(0x1f); printf("death\n"); for (;;) ; }
#
# V8's boot() calls update(), prints `syncing disks... ', and sleeps five
# lbolt ticks for the I/O to drain.  V10 deleted all of it -- RB_NOSYNC is
# defined in lsys/sys/reboot.h and referenced NOWHERE -- so on a Tenth Edition
# machine the userland sync is the only flush there is, and `sleep' is not a
# convenience but the wait that V8 does inside the kernel and V10 does not do
# at all.  sync(2) -> update() -> bflush(NODEV) issues B_ASYNC writes and
# returns (lsys/io/bio.c:692), so without the wait the disk is stopped with
# blocks still in core.
SHUTDOWN = ["halt", "sleep"]

# The tools the BOOTSTRAP ITSELF needs, none of which the first golden has.
#
# Measured, not guessed: the golden carries 57 prebuilt 1995 binaries plus
# what BOOTPATH builds, and `ar', `cmp', `tail', `grep' and `wc' are in
# neither set.  Two of those are not conveniences --
#
#	ar    stage 2 IS an archive.  libc.a cannot be built without it, and
#	      the preamble's `AR = /bin/ar' names a file that does not exist.
#	cmp   stage 3 IS a comparison.  The fixpoint is "stage 1 and stage 3
#	      produced the same bytes", so with no cmp there is no stage 3 --
#	      only an assertion that both runs exited zero, which is the kind
#	      of check this project has already been caught by.
#
#	ed    stage 2 EDITS A COMPILED FILE.  libc's errlst.o is compiled to
#	      assembly, run through gen/:errfix, and only then assembled -- the
#	      tape's own recipe, and :errfix is an ed script.  Without ed the
#	      error table stays in .data instead of shared text, which builds
#	      and runs and is not what Bell Labs shipped.
#
# `tail' is a convenience and is here anyway, because without it a failed
# build in a guest harness can only be shown with `cat' of a whole log, and
# the alternative to showing it is halting the machine that holds the only
# copy.
#
# ed is cmd/ed.c, the LOOSE one -- there is also a cmd/ed/ed.c carrying
# ansi.h and posix.h, and source_for() prefers the loose file.  That is the
# right one here for a reason and not by luck: the loose ed.c includes only
# <signal.h> and <setjmp.h> and has no prototype in it, so pcc2 can compile
# it, while the cmd/ed/ version is the POSIX rewrite.
BUILDTOOLS = ["ar", "cmp", "tail", "ed"]

# The compiler, from source.  THIS IS WHAT STAGE 1 IS.
