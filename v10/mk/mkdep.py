def libc_from_tape():
    """The build plan for libc, read off the tape rather than typed.

    Returns (order, objmap, lcc):
      order   member order of the tape's own libc.a, __.SYMDEF removed
      objmap  object -> source path, relative to src/libc
      lcc     the objects whose recipe the mkfile overrides with lcc
    """
    d = os.path.join(SRC, LIBC_DIR)
    mkf = os.path.join(d, "mkfile")
    arc = os.path.join(d, "libc.a")
    for p in (mkf, arc):
        if not os.path.exists(p):
            sys.exit("mkdep: no %s -- run tools/v10-import.py" % p)

    text = open(mkf).read()
    m = re.search(r"^OBJ=(.*?)(?=\n[A-Z])", text, re.S | re.M)
    if not m:
        sys.exit("mkdep: %s has no OBJ= list" % mkf)
    objs = re.findall(r"\$L\(([^)]+)\)", m.group(1))

    # object -> source, plus whichever recipe line follows it.  mk's own
    # syntax: a target line at column 0, its recipe indented with a tab.
    objmap, lcc, cur = {}, set(), None
    for line in text.splitlines():
        r = re.match(r"^([A-Za-z_0-9]+\.o):[ \t]+([^\s:]+)", line)
        if r:
            cur, objmap[r.group(1)] = r.group(1), r.group(2)
            continue
        if line.startswith("\t"):
            if cur and "lcc" in line.split():
                lcc.add(cur)
            continue
        cur = None

    order, data, off = [], open(arc, "rb").read(), 8
    if data[:8] != b"!<arch>\n":
        sys.exit("mkdep: %s is not an ar archive" % arc)
    while off + 60 <= len(data):
        h = data[off:off + 60]
        if h[58:60] != b"`\n":
            sys.exit("mkdep: %s: bad member header at byte %d" % (arc, off))
        name = h[0:16].decode().rstrip()
        size = int(h[48:58].decode().strip())
        if name != "__.SYMDEF":
            order.append(name)
        off += 60 + size + (size & 1)

    # THE TWO ARTEFACTS MUST AGREE, and a mismatch stops the generator.  A
    # tarball re-import that changed either one would otherwise produce a
    # makefile that builds a library nobody shipped, and the difference would
    # not show up until something failed to link much later.
    gap = [o for o in objs if o not in objmap]
    if gap:
        sys.exit("mkdep: %s lists %s in OBJ with no source line"
                 % (mkf, " ".join(gap)))
    if set(order) != set(objs):
        only_a = sorted(set(order) - set(objs))
        only_m = sorted(set(objs) - set(order))
        sys.exit("mkdep: the tape's libc.a and its mkfile disagree -- "
                 "only in the archive: %s; only in the mkfile: %s"
                 % (" ".join(only_a) or "none", " ".join(only_m) or "none"))
    return order, objmap, sorted(lcc)


def libc_built():
    """The members we compile: the tape's order, less LIBC_DROP.

    ONE function, so `libc.ord', `libc.src' and OBJS cannot disagree.  A
    component list that appears twice will disagree eventually and the
    disagreement is silent -- that is already written up in v10drive.exp, where
    an out-of-date Tcl copy of BUILDTOOLS made stage 1 skip `ed' and report
    42/44 with no line naming the cause.
    """
    order, objmap, _lcc = libc_from_tape()
    stray = [o for o in LIBC_DROP if o not in order]
    if stray:
        sys.exit("mkdep: LIBC_DROP names %s, which is not a libc member -- a "
                 "typo here silently drops nothing and builds everything"
                 % " ".join(stray))
    keep = [o for o in order if o not in LIBC_DROP]
    return keep, objmap


def emit_libc():
    order, objmap = libc_built()
    lcc = LIBC_LCC
    lccset = set(lcc) - set(LIBC_OURS)
    oursset = set(LIBC_OURS)
    both = set(LIBC_OURS) & set(lcc)
    if both:
        sys.exit("mkdep: %s is in both LIBC_OURS and LIBC_LCC -- a member "
                 "converted to K&R does not need lcc" % " ".join(sorted(both)))
    unknown = lccset - set(order)
    if unknown:
        sys.exit("mkdep: LIBC_LCC names %s, which is not a libc member"
                 % " ".join(sorted(unknown)))
    d = os.path.join(SRC, LIBC_DIR)
    srcdir = "$(SRC)/" + LIBC_DIR

    ourdir = os.path.join(OURS, LIBC_DIR)

    def dep(path):
        path = os.path.normpath(path)
        if path.startswith(INC + os.sep):
            return "$(INCDIR)/" + mkgen.rel(path, INC)
        # A HEADER IN THE OVERLAY MUST BE NAMED $(OURS), not walked to from
        # $(SRC).  An overlay source's quoted `#include "fconv.h"' resolves next
        # to that source, so the scanner hands back a path under v10/src/, and
        # relativising it against the pristine tree produced
        #
        #	$(SRC)/libc/../../../../v10/src/libc/stdio/fconv.h
        #
        # -- a prerequisite naming a file that does not exist on the guest at
        # all, so make answers `Don't know how to make' and the member never
        # compiles.  Only an OVERLAY header can reach here, since the pristine
        # tree is what $(SRC) is.
        if path.startswith(ourdir + os.sep):
            return "$(OURS)/" + LIBC_DIR + "/" + mkgen.rel(path, ourdir)
        return srcdir + "/" + mkgen.rel(path, d)

    # -DV10, WHICH THE TAPE'S OWN cc RULE DOES NOT PASS AND ITS lcc RULE DOES.
    #
    # `libc/mkfile' line 123 is the default recipe for every C member:
    #
    #	cc -O -c $prereq
    #
    # no -D and no -I.  Its lcc recipe, line 69, is
    #
    #	LCCARGS = -c -N -Istdio -I/usr/include/lcc -I/usr/include/libc \
    #	          -I/usr/include -DV10
    #
    # So `-DV10' IS this tree's answer -- it simply never reached the cc rule,
    # and that is another face of the unfinished V9-to-V10 port rather than an
    # oversight we should copy.  Without it:
    #
    #   * `stdio/iolib.h' takes its `#else' branch, which is the pANS one, and
    #     demands <stdlib.h> and <unistd.h> -- NEITHER OF WHICH EXISTS at the
    #     top level of the r70 include tree.  So the branch cannot be the
    #     intended one on this machine; it fails as
    #     `iolib.h: 34: Can't find include file stdlib.h'.
    #   * every `#ifdef V10' block in the sources is skipped, including the
    #     ones our own converted members depend on -- sprintf.c's hand-built
    #     `FILE _strbuf' becomes a call to `sopenw()', which does not exist,
    #     and fprintf.c loses `#define flags _flag'.
    #
    # A MAKEFILE DEVIATION, NOT A SOURCE ONE, and that is the right place for
    # it: V10 never had these makefiles, so they are ours to get right, and no
    # line of Bell Labs' source changes.
    out = [PREAMBLE % dict(name="libc", cflags="-DV10", incs="")]
    out.append("""\
# Not in the shared preamble because libc is the only thing that needs it.
# ranlib writes __.SYMDEF, and cmd/ld.c reads it: with a current one ld makes
# as many passes as it takes, without one it makes exactly one and warns.
RANLIB = /usr/bin/ranlib

# THE SECOND COMPILER, AND IT IS NOT A CONCESSION.  V10 was never built from
# scratch, so its per-file compiler requirement is mixed: 25 of these 261
# members are ANSI and pcc2 cannot parse them.  lcc is Bell Labs' own 1995
# binary off the same tape -- the same provenance as ccom and as -- and its
# driver's paths are compiled in, so it must be installed as /usr/bin/lcc
# with /usr/lib/rcc and /usr/lib/gcc-cpp beside it.
#
# LCCARGS is the tape's own, from libc/mkfile, less the -c it adds per rule.
LCC     = lcc
LCCPATH = /usr/bin/lcc
LCCARGS = -N -I$(SRC)/libc/stdio -I$(INCDIR)/lcc -I$(INCDIR)/libc -I$(INCDIR) -DV10

""")
    out.append("# The %d members compiled by $(LCC), because pcc2 cannot parse them.\n"
               % len(lcc))
    out.append("# Measured by tools/v10-stage2.sh, NOT read from the mkfile -- which\n"
               "# names only ten and is wrong about fifteen.  See mkdep.py.\n")
    out.append("#   " + " ".join(sorted(lcc)) + "\n\n")
    if LIBC_DROP:
        out.append("# The tape's libc.a has %d members; this builds %d.  NOT built, "
                   "by name:\n#   %s\n"
                   % (len(order) + len(LIBC_DROP), len(order),
                      " ".join(LIBC_DROP)))
        out.append("# A named exclusion, not an omission -- see LIBC_DROP in "
                   "v10/mk/mkdep.py for the\n"
                   "# grounds.  <sys/share.h> is reconstructible from nothing, and "
                   "nothing we build\n# calls it.\n\n")
    out.append("OBJS = " + " ".join(order) + "\n")
    out.append("""
all: libc.a crt0.o mcrt0.o

# The objects alone, so a driver can run `make -k objs' and find out how many
# of the 261 this compiler can build BEFORE anything depends on all of them.
# Without it a single member that will not compile takes the whole run down
# to nothing -- no archive, no comparison, no measurement, four hours gone.
objs: $(OBJS)

# TWO RULES, AND THE STAMP FILE IS THE REASON.  `ld -x -r' REWRITES each
# object in place, so doing it inside the libc.a recipe leaves all 261
# prerequisites newer than the archive the moment the recipe finishes -- the
# install pass then rebuilds the whole thing a second time and an incremental
# build never converges.  `stripped' is written after the objects it rewrote,
# so it is newer than all of them and libc.a is newer than it.
#
# The loop is over *.o and not over $(OBJS), which matters after a `make -k'
# that could not build every member: the strip pass then covers what exists
# instead of stopping at the first name with no file.
stripped: $(OBJS)
	-for i in *.o ; do $(LD) -x -r $$i; mv a.out $$i; done
	echo stripped > stripped

# `cr' and not `uv': the member order is the tape's, and an update would
# append anything missing at the end instead.  rm first, because `cr' on an
# existing archive replaces members rather than starting over.
libc.a: stripped
	rm -f libc.a
	$(AR) cr libc.a $(OBJS)
	$(RANLIB) libc.a

# gen/:errfix moves the error-message table out of .data and into shared
# text: errlst.c is compiled to ASSEMBLY, edited, and only then assembled.
# The filename really does begin with a colon -- a V7 convention for a script
# that is not a command you would type.
#
# -S rather than -c, and the output lands HERE and not on the share: cc.c's
# setsuf() walks the path and returns the basename, so `cc -S /n/v10/src/...
# /errlst.c' writes errlst.s into the object directory.  That is what makes
# the whole out-of-tree build possible and it is worth knowing where it comes
# from.
errlst.o: %(src)s/gen/errlst.c $(TOOLS)
	$(CC) $(CFLAGS) $(INCS) -S %(src)s/gen/errlst.c
	ed - errlst.s < %(src)s/gen/:errfix
	$(AS) -o errlst.o errlst.s
	rm -f errlst.s
""" % dict(src=srcdir))

    # crt0.o and mcrt0.o are built here but are NOT members: they are the
    # startup files ld links in front of every program.
    for obj in order + ["crt0.o", "mcrt0.o"]:
        if obj == "errlst.o":
            continue
        src = objmap.get(obj, "csu/" + obj[:-2] + ".s")
        # OUR copy, where there is one -- and the rule SAYS so, which is the
        # whole reason provenance lives in the makefile rather than a comment.
        if obj in oursset:
            path = os.path.join(OURS, LIBC_DIR, src)
            here = "$(OURS)/" + LIBC_DIR
        else:
            path = os.path.join(d, src)
            here = srcdir
        deps = [here + "/" + src] + [
            x for x in sorted(dep(y) for y in mkgen.scan_includes(path, [INC]))
            # `dep()' resolves against the pristine tree, so an overlay source
            # comes back as a relative walk out of $(SRC).  Filter the file
            # itself by NAME, not by the one spelling we happened to expect.
            if not x.endswith("/" + src)]
        if obj in lccset:
            # $(LCCPATH), not $(TOOLS): this object does not go through ccom,
            # c2 or cpp at all, so naming them as prerequisites would rebuild
            # it whenever a pass it never runs changes.
            out.append("\n%s: %s $(LCCPATH)\n\t$(LCC) $(LCCARGS) -c %s/%s\n"
                       % (obj, " ".join(deps), srcdir, src))
        elif obj in oursset:
            # AN OVERLAY SOURCE NEEDS ITS ORIGINAL'S NEIGHBOURHOOD ON THE
            # INCLUDE PATH, and this is the whole reason the first attempt at
            # B2.2c built nothing.
            #
            # `#include "iolib.h"' is a QUOTED include, so cpp looks in the
            # directory of the INCLUDING FILE first -- which for a pristine
            # member is $(SRC)/libc/stdio/, where iolib.h lives.  Our copy sits
            # in $(OURS)/libc/stdio/ instead, and $(INCS) is only
            # `-I$(INCDIR)', so from there iolib.h is nowhere: cpp fails, no
            # object appears, and `make -k' moves on.  The member then shows up
            # in the MISS list with NO compiler error line anywhere -- which
            # reads exactly like make never running the rule at all.
            #
            # So the rule adds -I on the directory the original occupies.  It
            # is per-rule and not global on purpose: $(INCS) is shared by all
            # 261 members, and $(SRC)/libc/stdio also holds a `stdio.h'-adjacent
            # private header set that has no business shadowing the system's.
            out.append("\n%s: %s $(TOOLS)\n\t$(COMPILE) -I%s %s/%s\n"
                       % (obj, " ".join(deps),
                          srcdir + "/" + os.path.dirname(src), here, src))
        else:
            out.append("\n%s: %s $(TOOLS)\n\t$(COMPILE) %s/%s\n"
                       % (obj, " ".join(deps), here, src))

    # Into $(TOOLDIR)/lib, never over the libc being compiled against.  The
    # tape's own install target opens `cp $(DESTDIR)/lib/libc.a liboc.a; cp
    # libc.a $(DESTDIR)/lib/libc.a' -- it overwrites the running system's.
    out.append("\ninstall: libc.a crt0.o mcrt0.o\n")
    out.extend(mkgen.mkdirs_for("$(TOOLDIR)", "lib/libc.a"))
    out.append("\tcp libc.a $(TOOLDIR)/lib/libc.a\n")
    # RANLIB AFTER THE COPY.  cp gives the archive a new mtime while __.SYMDEF
    # keeps the old one, and ld reads that as "table of contents out of date"
    # -- one sequential pass, a warning naming ranlib, and undefined symbols
    # in something that linked fine a minute earlier.
    out.append("\t$(RANLIB) $(TOOLDIR)/lib/libc.a\n")
    out.append("\tcp crt0.o $(TOOLDIR)/lib/crt0.o\n")
    out.append("\tcp mcrt0.o $(TOOLDIR)/lib/mcrt0.o\n")
    out.append("\nclean:\n\t-rm -f $(OBJS) crt0.o mcrt0.o libc.a stripped\n")
    return "".join(out)


