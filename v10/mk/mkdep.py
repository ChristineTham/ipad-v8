def mux_jerq_map():
    """-> {include name: host path} for our /usr/jerq/include, exactly.

    THE HOST MODEL MUST MATCH WHAT THE GUEST GETS, or the makefile names a
    prerequisite that does not exist and make answers `Don't know how to
    make' -- the app's `it is in the golden, it will arrive on Reset' lesson
    in a third place.  So this is built from the two things that actually
    install: the 21-file blit include tree that tools/v10drive.exp's
    v10_jerq_inc copies, and MUX_INC above.
    """
    m = {}
    blit = os.path.join(ROOT, "work/v10/blit/include")
    if os.path.isdir(blit):
        for f in sorted(os.listdir(blit)):
            p = os.path.join(blit, f)
            if os.path.isfile(p):
                m[f] = p
    for name, prov, rel in MUX_INC:
        m[name] = os.path.join(SRC if prov == "tape" else OURS, rel)
    # Our overlay's jioctl.h wins, as v10_jerq_inc installs it -- it adds
    # `#define JMUX JMPX', an alias no header on the tape defines.
    ours = os.path.join(OURS, "include/jioctl.h")
    if os.path.exists(ours):
        m["jioctl.h"] = ours
    return m


def mux_closure(path, jerq, seen=None, chain=()):
    """Transitive include closure for one mux source, resolved as cpp will.

    Its own directory first for a quoted include, then proto/, then
    /usr/jerq/include, then the system tree -- the mkfile's `-I$INCL -I$JINCL'
    with /usr/include implicit last.

    UNLIKE mkgen.scan_includes() THIS RAISES on an include it cannot place.
    A dropped header is not a smaller dependency list, it is a build that
    compiles against something nobody chose.
    """
    if seen is None:
        seen = {}
    if path in seen or not os.path.exists(path):
        return seen
    seen[path] = True
    d = os.path.join(SRC, MUX_DIR)
    proto = os.path.join(d, "proto")
    own = os.path.dirname(path)
    for kind, raw in mkgen.INCLUDE.findall(open(path, "rb").read()):
        name = raw.decode("ascii", "replace")
        if name in MUX_UNREACHED:
            continue
        cands = [os.path.join(own, name)] if kind == b'"' else []
        cands += [os.path.join(proto, name)]
        if name in jerq:
            cands.append(jerq[name])
        cands.append(os.path.join(INC, name))
        for c in cands:
            c = os.path.normpath(c)
            if os.path.isfile(c):
                mux_closure(c, jerq, seen, chain + (name,))
                break
        else:
            raise SystemExit(
                "mkdep: mux: cannot resolve #include %s, reached via %s.\n"
                "  Either add it to MUX_INC with its provenance, or -- if it "
                "is behind a #ifdef this build never takes -- to "
                "MUX_UNREACHED with the reason." % (name, " -> ".join(chain) or path))
    return seen


def emit_mux():
    d = os.path.join(SRC, MUX_DIR)
    if not os.path.isdir(d):
        sys.exit("mkdep: no %s -- run tools/v10-import.py" % d)
    jerq = mux_jerq_map()
    for name, prov, rel in MUX_INC:
        p = os.path.join(SRC if prov == "tape" else OURS, rel)
        if not os.path.exists(p):
            sys.exit("mkdep: mux: MUX_INC names %s, which is not at %s" % (name, p))
    srcdir = "$(SRC)/" + MUX_DIR
    ixdir  = os.path.join(SRC, MUX_IX_DIR)
    ourdir = os.path.join(OURS, MUX_DIR)
    jerqpaths = {v: k for k, v in jerq.items()}

    # THREE SOURCE ROOTS NOW, and a dependency naming the wrong one is a rule make
    # cannot satisfy: `Make: Don't know how to make ...' for every object at once.
    # Each root is tested before the fallback rather than after it, because
    # mkgen.rel() against the wrong base yields a plausible-looking `../..' path
    # instead of an error.
    def dep(path):
        path = os.path.normpath(path)
        if path in jerqpaths:
            return "$(JERQINC)/" + jerqpaths[path]
        if path.startswith(INC + os.sep):
            return "$(INCDIR)/" + mkgen.rel(path, INC)
        if path.startswith(ixdir + os.sep):
            return "$(IXLIBC)/" + mkgen.rel(path, ixdir)
        if path.startswith(ourdir + os.sep):
            return "$(MUXOURS)/" + mkgen.rel(path, ourdir)
        return srcdir + "/" + mkgen.rel(path, d)

    out = [PREAMBLE % dict(
        name="mux",
        cflags="",
        incs="-I%s/proto -I$(JERQINC)" % srcdir)]
    out.append("""\
# THE 5620 INCLUDE TREE, WHICH IS A STAND-IN AND SAYS SO.  A real V10 machine
# had /usr/jerq from the separate 5620 distribution tape; the V10 golden has no
# /usr/jerq at all, so ours is the v10blit tarball's 21 headers -- the 68000
# Blit's -- plus the %d this build needs that no surviving tree provides at the
# path mux names.  tools/v10drive.exp's v10_jerq_inc installs the 21 and
# v10/mk/gen/mux.inc names the rest.
JERQINC = /usr/jerq/include

# IX's own libc sources, and ours.  labEQ/labLE are Bell Labs' and unchanged;
# muxix.c is ours and carries its argument in v10/src/PATCHES.md.
IXLIBC  = $(SRC)/%s
MUXOURS = $(OURS)/%s

""" % (len(MUX_INC), MUX_IX_DIR, MUX_DIR))
    out.append("OBJS = " + " ".join(o for o, _ in MUX_OBJS + MUX_IX + MUX_OURS)
               + "\n")
    out.append("\nall: mux\n")
    out.append("\nmux: $(OBJS) $(LD) $(LIBC)\n"
               "\t$(CC) $(CFLAGS) -o mux $(OBJS) $(LIBC)\n")
    for obj, src in MUX_OBJS:
        full = os.path.join(d, src)
        deps = sorted(dep(p) for p in mux_closure(full, jerq)
                      if os.path.normpath(p) != os.path.normpath(full))
        # `pcheck.c' includes NOTHING -- it is the CRC, and its vax arm is
        # four asm() lines -- so its dependency list is empty and a plain
        # format string leaves a double space behind.
        out.append("\n%s: %s\n\t$(COMPILE) %s/%s\n"
                   % (obj, " ".join(["%s/%s" % (srcdir, src)] + deps
                                    + ["$(TOOLS)"]), srcdir, src))
    # The IX libc members and our glue, each from its own root.
    for objs, root, var in ((MUX_IX, ixdir, "$(IXLIBC)"),
                            (MUX_OURS, ourdir, "$(MUXOURS)")):
        for obj, src in objs:
            full = os.path.join(root, src)
            if not os.path.exists(full):
                sys.exit("mkdep: mux: no %s -- %s" % (full,
                         "run tools/v10-overlay.py" if var == "$(MUXOURS)"
                         else "run tools/v10-import.py"))
            deps = sorted(dep(pp) for pp in mux_closure(full, jerq)
                          if os.path.normpath(pp) != os.path.normpath(full))
            out.append("\n%s: %s\n\t$(COMPILE) %s/%s\n"
                       % (obj, " ".join(["%s/%s" % (var, src)] + deps
                                        + ["$(TOOLS)"]), var, src))
    out.append("\ninstall: mux\n")
    out.extend(mkgen.mkdirs_for("$(DESTDIR)", "usr/jerq/bin/mux"))
    out.append("\tcp mux $(DESTDIR)/usr/jerq/bin/mux\n")
    out.append("\nclean:\n\t-rm -f $(OBJS) mux\n")
    return "".join(out)


def source_for(name, root):
    """Where this command's source is: cmd/<name>.c, or cmd/<name>/<name>.c."""
    loose = os.path.join(root, "cmd", name + ".c")
    if os.path.exists(loose):
        return "cmd", name + ".c"
    indir = os.path.join(root, "cmd", name, name + ".c")
    if os.path.exists(indir):
        return "cmd/" + name, name + ".c"
    return None, None


def component(name):
    """One entry for mkgen.emit(), or None with a reason."""
    # A host tool is `v10<something>'; its SOURCE is the unprefixed name.
    host = name.startswith("v10")
    srcname = name[3:] if host else name
    patched = srcname in PATCHED
    root = OURS if patched else SRC
    d, src = source_for(srcname, root)
    if d is None:
        if patched:
            return None, ("listed as patched but not in v10/src -- "
                          "run tools/v10-overlay.py")
        return None, "no source in cmd/"
    if host:
        # Host tools land beside the V10 toolchain, never on V8's PATH, and
        # under TOOLDIR rather than the image's DESTDIR.
        c = dict(name=name, dir=d, objs=[src], product=name,
                 install="bin/" + name, dest="TOOLDIR")
        if patched:
            c["root"], c["srcmacro"] = OURS, "OURS"
        return c, None
    where = WHERE.get(srcname)
    if not where:
        return None, "no install path (tools/v10-where.py says unresolved)"
    c = dict(name=name, dir=d, objs=[src], product=name,
             install=where[0].lstrip("/") + "/" + name, dest="DESTDIR")
    if patched:
        # Read from the overlay, and SAY SO in the generated rule.  The point
        # is that provenance survives into the artefact: someone reading
        # gen/fsck.mk in a year can see at a glance that this one source is
        # ours and every other is Bell Labs'.
        c["root"] = OURS
        c["srcmacro"] = "OURS"
    return c, None


def kernel_objects():
    """Which kernel objects does v10/src/ patch, and which archive holds each?

    DERIVED, NEVER RESTATED.  K6/K7 compile only the generated conf.c and low.s
    and link the tape's PREBUILT per-subsystem archives, so a patch to a kernel
    source changes nothing until its object is recompiled and replaced.  Both
    halves of that are questions the tape answers: the sources are whatever
    v10/src/lsys/ carries, and which archive owns an object is what `ar t' says.
    A hand-written list would be a third copy of a fact already stated twice,
    and this project has watched one of those disagree in silence.

    -> [(source relpath, object name, archive name)], in source order.
    """
    lib = os.path.join(SRC, "lsys", "lib")
    ours = os.path.join(OURS, "lsys")
    if not os.path.isdir(ours) or not os.path.isdir(lib):
        return []
    members = {}
    for a in sorted(os.listdir(lib)):
        if not a.endswith(".a"):
            continue
        out = subprocess.run(["ar", "t", os.path.join(lib, a)],
                             capture_output=True, text=True)
        for m in out.stdout.split():
            members.setdefault(m, a)
    rows = []
    for dirpath, _dirs, files in os.walk(ours):
        for f in sorted(files):
            if not f.endswith(".c"):
                continue
            obj = f[:-2] + ".x"
            if obj not in members:
                continue
            rel = os.path.relpath(os.path.join(dirpath, f), OURS)
            rows.append((rel, obj, members[obj]))
    return sorted(rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the committed makefiles are stale")
    args = ap.parse_args()

    if not os.path.isdir(SRC):
        sys.exit("mkdep: no %s -- run tools/v10-import.py" % SRC)

    os.makedirs(GEN, exist_ok=True)
    stale, written, entries, skipped = [], set(), [], []

    def put(name, text):
        # FOURTEEN BYTES.  Every file generated here is copied onto a guest
        # filesystem, and a Research Unix directory entry is 14 characters --
        # a longer name is TRUNCATED, silently, with a successful exit status.
        #
        # `toolchain.order' is 15 and arrived on the source disk as
        # `toolchain.orde', which read as a copy that had not happened.  This
        # is the project's fourth time: `streamio.c.orig' (15) failed with a
        # bare "cp: cannot create", and `install-prebuilt.sh' (19) with
        # "sh: cannot open".  Each was fixed and none of them stopped the
        # next one, so the rule goes in the generator rather than in a
        # comment.
        if len(name) > 14:
            raise SystemExit(
                "mkdep: '%s' is %d characters -- a Research Unix directory "
                "entry is 14, so this name is silently truncated to '%s' the "
                "moment it reaches a guest.  Shorten it."
                % (name, len(name), name[:14]))
        if name in written:
            raise SystemExit("mkdep: two components both generate %s" % name)
        written.add(name)
        path = os.path.join(GEN, name)
        old = open(path).read() if os.path.exists(path) else None
        if args.check:
            if old != text:
                stale.append(name)
        elif old != text:
            open(path, "w").write(text)

    for name in BOOTPATH + FSTOOLS + SHUTDOWN + BUILDTOOLS + TOOLCHAIN_SIMPLE:
        c, why = component(name)
        if c is None:
            skipped.append((name, why))
            continue
        put(name + ".mk", mkgen.emit(V10ED, c))
        entries.append((name, c["dir"], c["install"]))

    # The multi-file toolchain components carry their own dicts: each is a
    # DIRECTORY of sources with no <name>.c, so component()'s heuristic --
    # which finds every ordinary command -- finds none of the compiler.
    tcnames = []
    for c in TOOLCHAIN:
        put(c["name"] + ".mk", mkgen.emit(V10ED, c))
        entries.append((c["name"], c["dir"], c["install"]))
        tcnames.append(c["name"])

    # STAGE 2.  An archive, not a program, so it has its own emitter rather
    # than a component dict -- see emit_libc().
    put("libc.mk", emit_libc())
    entries.append(("libc", LIBC_DIR, "lib/libc.a"))
    # The member list as DATA, in the tape's own order, so the guest can walk
    # it from `sh'.  A driver has to answer "which of the 261 are missing?"
    # and V10 has no wc and no grep -- what it does have is a for loop, and
    # this is the file it reads.
    # THE 260 WE BUILD, not the tape's 261: setupshares.o is a named exclusion
    # (LIBC_DROP), so a driver walking this file asks "did everything I build
    # compile?" -- a question with a yes -- instead of "did all 261 compile?",
    # which could only ever answer no.  See LIBC_DROP for why that mattered.
    put("libc.ord", "".join(o + "\n" for o in libc_built()[0]))
    # And the exclusions themselves, as data, so the harness and the wrapper
    # both read them rather than restating "setupshares" in Tcl and in bash.
    put("libc.drop", "".join(o + "\n" for o in LIBC_DROP))
    # object -> source, as DATA, so the guest can compile one member by name
    # without a makefile.  `sed -n "s/^$o //p" libc.src' is the whole lookup.
    #
    # This is what lets stage 2 ask the question that matters about a member
    # whose bytes differ from the tape's: WHICH COMPILER did Bell Labs use?
    # Recompile it with lcc, strip it the way the tape does, and compare
    # again -- a match names the compiler, and a set of such matches turns
    # "V10 was never built from scratch" from a warning into a map.
    _order, _objmap = libc_built()
    put("libc.src", "".join("%s %s\n" % (o, _objmap[o]) for o in _order))

    # RUNG 8's HOST HALF -- its own emitter, for the reasons above emit_mux().
    put("mux.mk", emit_mux())
    entries.append(("mux", MUX_DIR, "usr/jerq/bin/mux"))
    # The five headers, as DATA with their provenance, so the harness applies a
    # list rather than restating five copies in Tcl.  inc.extra's lesson, one
    # directory over: a list that appears twice will disagree, and the copy
    # that disagreed was the one nobody ran.
    put("mux.inc",
        "# The headers mux needs that /usr/jerq/include does not carry.\n"
        "# Generated by v10/mk/mkdep.py -- see MUX_INC for the evidence\n"
        "# behind each choice.  Destination is /usr/jerq/include, never\n"
        "# /usr/include: these are the NINTH edition's path convention.\n"
        "#\n"
        "# fields: installed-name  tape|ours  path-within\n"
        # TAB-separated, because v10_rows() in tools/v10drive.exp splits on tab
        # and checks the column count -- aligned spaces gave it one column and it
        # bailed with "has 1 columns, expected 3".  Same shape as bootpath.order.
        + "".join("%s\t%s\t%s\n" % (n, w, f) for n, w, f in MUX_INC))

    put("bootpath.order",
        "".join("%s\t%s\t%s\n" % e
                for e in entries if e[0] in BOOTPATH))
    put("fstools.order",
        "".join("%s\t%s\t%s\n" % e
                for e in entries if e[0] in FSTOOLS))
    put("shutdown.order",
        "".join("%s\t%s\t%s\n" % e
                for e in entries if e[0] in SHUTDOWN))
    put("buildtools.ord",
        "".join("%s\t%s\t%s\n" % e
                for e in entries if e[0] in BUILDTOOLS))
    # ORDER IS THE POINT HERE, unlike the lists above.  yacc must exist before
    # cpp or ccom can be built from a grammar, and every later pass is built
    # by the passes before it, so this file is a sequence and not a set.
    tcorder = tcnames + [n for n in TOOLCHAIN_SIMPLE if n in dict(
        (e[0], e) for e in entries)]
    # THE KERNEL OBJECTS OUR OVERLAY PATCHES.  Three columns: source under
    # v10/src, the object name, the tape archive that owns it.  Empty when the
    # overlay patches no kernel source, which is the normal state.
    put("kobj.order",
        "".join("%s\t%s\t%s\n" % r for r in kernel_objects()))

    put("tc.order",
        "".join("%s\t%s\t%s\n" % dict((e[0], e) for e in entries)[n]
                for n in tcorder))

    # What was NOT covered, and why -- generated rather than commented, so it
    # cannot drift from the code that produced it.  A build that silently
    # covers less than it appears to is worse than one that covers less and
    # says so; V8's stage 6 shipped `bcd' built, reported, and absent because
    # of exactly this gap.
    put("bootskip.txt",
        "# Boot-path commands v10/mk/mkdep.py did not emit a makefile for.\n"
        "# Regenerated by v10/mk/mkdep.py.\n#\n"
        + "".join("%-10s %s\n" % s for s in skipped))

    # NOTHING MAY WRITE OUTSIDE A MACRO, and nothing may write to `/'.
    # These makefiles run on a live Eighth Edition host with its own mkfs,
    # mknod, dd and cpio; a rule that reached /bin or /lib would replace a
    # V8 tool with a V10 one and the damage would surface much later.
    import re as _re
    for name in sorted(written):
        if not name.endswith(".mk"):
            continue
        text = open(os.path.join(GEN, name)).read()
        for line in text.splitlines():
            m = _re.match(r"\t(?:-mkdir|cp|mv)\s+(.*)", line)
            if not m:
                continue
            dest = m.group(1).split()[-1]
            # A BARE FILENAME IS THE OBJECT DIRECTORY, and that is where a
            # build is supposed to write.  ccom's `cp $(SRC)/.../y.debug.sv
            # y.debug' is the case: the tape needs y.debug beside the object,
            # and naming it through a macro would put it somewhere else.
            #
            # What must go through a macro is anything that NAMES a location
            # -- an absolute path, or a relative one that walks out of here.
            # That is the whole of the risk: this build runs on a live Eighth
            # Edition host, so `cp c2 /lib' would replace V8's peephole
            # optimiser with V10's and the damage would surface later,
            # somewhere else, in something that had been working.
            if "/" in dest and not dest.startswith("$("):
                raise SystemExit(
                    "mkdep: %s writes to a literal path (%s) -- a destination "
                    "naming a directory must go through $(DESTDIR) or "
                    "$(TOOLDIR)" % (name, dest))
    for macro in ("DESTDIR", "TOOLDIR"):
        if ("\n%-8s= /" % macro).replace("%-8s", macro.ljust(8)) not in PREAMBLE:
            raise SystemExit("mkdep: PREAMBLE has no absolute %s default; an "
                             "empty one would write into the host's /" % macro)

    if args.check:
        if stale:
            print("stale, re-run v10/mk/mkdep.py: " + " ".join(stale))
            return 1
        print("makefiles are up to date with the source tree")
        return 0

    print("generated %d of %d components in %s"
          % (len(entries),
             len(BOOTPATH) + len(FSTOOLS) + len(SHUTDOWN)
             + len(BUILDTOOLS) + len(TOOLCHAIN_SIMPLE) + len(TOOLCHAIN)
             # the two with hand-written emitters: libc (an archive) and mux
             # (seven objects across two directories).  A bare `+ 1' here
             # printed "42 of 41" the moment mux was added.
             + 2,
             mkgen.rel(GEN, os.getcwd())))
    order, _, lcc = libc_from_tape()
    built, _ = libc_built()
    print("  libc       %d members on the tape, %d built here (order read from "
          "the tape's libc.a); %d built with lcc there"
          % (len(order), len(built), len(lcc)))
    if LIBC_DROP:
        print("  libc       NOT built, by name: %s" % " ".join(LIBC_DROP))
    if skipped:
        for name, why in skipped:
            print("  skipped %-10s %s" % (name, why))
    if not WHERE:
        print("  NO v10/mk/where.txt -- run tools/v10-where.py")
    return 0


if __name__ == "__main__":
    sys.exit(main())
