#!/usr/bin/env bash
#
# Build the first Tenth Edition golden image.  Phase K6.
#
#	tools/v10-golden.sh [v8-image]
#
# Produces work/v10gold/ipnx-v10-ra81.img: a bootable RA81 carrying a Tenth
# Edition root and /usr, assembled from the tape's own binaries plus the
# commands we build from its source.
#
# THE PARTITION LAYOUT IS THE TAPE'S.  lsys/io/ra.c's ra_sizes[] and seki.m's
# root/swap lines together fix it:
#
#	a   10240 sectors at      0    5 MB   root  (`root regfs ra 0100')
#	b   20480 sectors at  10240   10 MB   swap  (`swap ra 01 20480')
#	c  249848 sectors at  30720  122 MB   /usr (we use 246016 of it)
#
# Each filesystem is built in its OWN file at offset zero, because V8's hp
# partition table and V10's ra table disagree about where anything starts.
# The offsets are applied here, on the host, where they can be shown.
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
source "$ROOT/tools/v8clone.sh"

TPORT="${TPORT:-9260}"; OPORT="${OPORT:-9261}"
MPORT="${MPORT:-9262}"; SPORT="${SPORT:-9263}"
GOLD="$ROOT/work/v10gold"
SCRATCH="$GOLD/scratch"
NETFSD="$ROOT/netfs/.build/release/netfsd"
PIDS=()

# sectors, from ra_sizes[]
ROOT_SECTORS=10240
USR_OFFSET=30720
USR_SECTORS=246016   # 30752 blocks of 4096 -- MAXSMALL, see v10-golden.exp

cleanup() {
    for pid in "${PIDS[@]:-}"; do
        [[ -n "$pid" ]] && kill "$pid" 2>/dev/null && wait "$pid" 2>/dev/null
    done
    true
}
trap cleanup EXIT

[[ -d "$ROOT/work/v10" ]] || { echo "v10-golden: no work/v10 -- run tools/v10-import.py"; exit 1; }
pgrep -x vax780 >/dev/null && { echo "v10-golden: a vax780 is already running"; exit 1; }

python3 "$ROOT/tools/v10-overlay.py"  --check || { echo "regenerate the overlay first"; exit 1; }
python3 "$ROOT/v10/mk/mkdep.py"       --check || { echo "regenerate the makefiles first"; exit 1; }
python3 "$ROOT/tools/v10-prebuilt.py" --check || { echo "regenerate prebuilt.txt first"; exit 1; }
python3 "$ROOT/tools/v10-proto.py"    --check || { echo "regenerate proto-dev first"; exit 1; }
python3 "$ROOT/tools/v10-uda750.py"   --check || { echo "regenerate the 750 ROM first"; exit 1; }

echo "== building netfsd =="
( cd "$ROOT/netfs" && swift build -c release ) >/dev/null || exit 1

rm -rf "$GOLD"; mkdir -p "$SCRATCH/etc"

# ---------------------------------------------------------------- /etc ---
#
# Written here rather than echoed into the guest: a here-document on the host
# is readable, and CANBSIZ is 256 so a long line typed at a V8 tty is silently
# discarded.
#
# /etc/ttys is V7's format, which V10's init still reads (cmd/init.c rline()):
# character 1 is the on/off flag, character 2 is the getty argument, and the
# rest is the tty name.
# The SECOND character is getty's argument, and it picks a row of itab[] in
# cmd/getty.c.  `0' is the first row -- ANYP+RAW at B300, succeeded by 1, 2,
# 3 -- so `10console' put the console in RAW mode at 300 baud and cycled.
# getty printed `login: ' and then never read a character, which reads as a
# dead machine and is a dead terminal line.
#
# `2' is the row the tape provides for this: `/* table '2' -- 9600 */', 9600
# both ways, and self-succeeding so it does not cycle speeds on a console
# that has only one.
cat > "$SCRATCH/etc/ttys" <<'EOF'
12console
02tty00
02tty01
02tty02
02tty03
02tty04
02tty05
02tty06
02tty07
EOF

cat > "$SCRATCH/etc/passwd" <<'EOF'
root::0:0:The Man,,,:/:/bin/sh
daemon::1:1:The Devil,,,:/:
bin::3:3:Binaries,,,:/bin:
EOF

cat > "$SCRATCH/etc/group" <<'EOF'
wheel:*:0:root
daemon:*:1:daemon
bin:*:3:bin
other:*:20:
EOF

cat > "$SCRATCH/etc/motd" <<'EOF'

Research UNIX, Tenth Edition.

Restored by ipnx from the 1995 CSRC source tape.  The kernel is seki --
`Unix 10e Mar 15 04:03 1990' -- linked at Bell Labs and never, until now,
booted from media anyone had.

EOF

cat > "$SCRATCH/etc/rc" <<'EOF'
PATH=/bin:/etc:/usr/bin
export PATH
/etc/mount /dev/ra0c /usr
cat /etc/motd
EOF

# ------------------------------------------------------ /dev, generated ---
#
# From v10/mk/gen/proto-dev, whose majors are seki.c.c's own tables and whose
# shape follows the V8 golden read with tools/v8fs.py.  Written as a script
# the guest runs, so the map stays reviewable here.  The name is short because
# V8 filenames are 14 bytes.
{
    echo '#!/bin/sh'
    echo '# generated by tools/v10-golden.sh from v10/mk/gen/proto-dev'
    echo 'R=$1'
    while IFS=$'\t' read -r name kind major minor mode; do
        [[ "$name" == \#* || -z "$name" ]] && continue
        echo "/etc/mknod \$R/dev/$name $kind $major $minor"
        echo "chmod $mode \$R/dev/$name"
    done < "$ROOT/v10/mk/gen/proto-dev"
} > "$SCRATCH/mkdev.sh"
echo "== $(grep -c '^/etc/mknod' "$SCRATCH/mkdev.sh") device nodes =="

# the /etc files proto-etc lists that are not already written above
cat > "$SCRATCH/etc/fstab" <<'EOF'
/dev/ra0a	/	rw	1 1
/dev/ra0c	/usr	rw	1 2
EOF
: > "$SCRATCH/etc/mtab"
: > "$SCRATCH/etc/utmp"
cat > "$SCRATCH/etc/profile" <<'EOF'
PATH=/bin:/usr/bin:/etc
export PATH
EOF

# ------------------------------------------- the prebuilt-command installer ---
#
# Generated from v10/mk/gen/prebuilt.txt so the guest runs a plain list rather
# than the logic that produced it, and so the map stays reviewable on the host.
# $1 = the served tree, $2 = root mount, $3 = /usr mount.
{
    echo '#!/bin/sh'
    echo '# generated by tools/v10-golden.sh from v10/mk/gen/prebuilt.txt'
    echo 'V=$1; R=$2; U=$3'
    while IFS=$'\t' read -r name inst src how size; do
        [[ "$name" == \#* || -z "$name" ]] && continue
        case "$inst" in
            usr/*) echo "cp \$V/$src \$U/${inst#usr/} && chmod 755 \$U/${inst#usr/}" ;;
            *)     echo "cp \$V/$src \$R/$inst && chmod 755 \$R/$inst" ;;
        esac
    done < "$ROOT/v10/mk/gen/prebuilt.txt"
} > "$SCRATCH/instpre.sh"
echo "== $(grep -c '^cp ' "$SCRATCH/instpre.sh") prebuilt commands to install =="

# ------------------------------------------------------- the two partitions ---
echo "== creating the partition files =="
dd if=/dev/zero of="$ROOT/work/myv8/v10root.part" bs=512 count=$ROOT_SECTORS 2>/dev/null
dd if=/dev/zero of="$ROOT/work/myv8/v10usr.part"  bs=512 count=$USR_SECTORS 2>/dev/null
ls -l "$ROOT/work/myv8/v10root.part" "$ROOT/work/myv8/v10usr.part" | awk '{printf "   %12d  %s\n", $5, $9}'

IMG=$(v8_clone "${1:-rp07new}" golden) || exit 1

serve() { "$NETFSD" -p "$1" ${4:-} "$2" > "$ROOT/work/netfs-$3.log" 2>&1 & PIDS+=($!); }
serve "$TPORT" "$ROOT/work/v10"   v10gtree
serve "$OPORT" "$ROOT/v10/src"    v10gours
serve "$MPORT" "$ROOT/v10/mk/gen" v10gmk
serve "$SPORT" "$SCRATCH"         v10gscratch -w
sleep 1
for pid in "${PIDS[@]}"; do
    kill -0 "$pid" 2>/dev/null || { echo "netfsd died"; tail -5 "$ROOT"/work/netfs-v10g*.log; exit 1; }
done

echo "== driving the guest =="
expect "$ROOT/tools/v10-golden.exp" "$IMG" "$TPORT" "$OPORT" "$MPORT" "$SPORT" 2>&1 \
    | tee "$ROOT/work/v10-golden.log"
rc=${PIPESTATUS[0]}

# ------------------------------------------------------------ assemble it ---
OUT="$GOLD/ipnx-v10-ra81.img"
echo
echo "== assembling $OUT =="
# RA81 = 891072 sectors.  The image is sized to the drive so SIMH's autosize
# picks RA81 rather than guessing from a short file.
dd if=/dev/zero of="$OUT" bs=512 count=891072 2>/dev/null
dd if="$ROOT/work/myv8/v10root.part" of="$OUT" bs=512 seek=0 conv=notrunc 2>/dev/null
dd if="$ROOT/work/myv8/v10usr.part"  of="$OUT" bs=512 seek=$USR_OFFSET conv=notrunc 2>/dev/null
# and the boot block, which lsys/boot/bb/mkfile says lives in sector 0
dd if="$ROOT/work/v10/src/lsys/boot/bb/4kb" of="$OUT" bs=512 count=1 conv=notrunc 2>/dev/null

printf '   root  at sector %6d  (%s)\n' 0 "$(du -h "$ROOT/work/myv8/v10root.part" | cut -f1)"
printf '   usr   at sector %6d  (%s)\n' $USR_OFFSET "$(du -h "$ROOT/work/myv8/v10usr.part" | cut -f1)"
printf '   image %s\n' "$(du -h "$OUT" | cut -f1)"
echo "   sha256 $(shasum -a 256 "$OUT" | cut -c1-16)"
echo "== v10-golden exit $rc =="
exit "$rc"
