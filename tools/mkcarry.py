#!/usr/bin/env python3
"""Decide where every file on the ipnx disk comes from, and prove it.

	tools/mkcarry.py [--image work/myv8/rp06v8.golden] [--check]

Writes three lists into v8/mk/gen/, which stage 8 consumes:

  carry.txt	take from the reference image, because NOTHING ELSE HAS IT.
		This is the retirement-critical set.
  fromgold.txt	take from the reference image because its copy is BYTE-
		IDENTICAL to ours and that path is ~900x faster.
  fromsrc.txt	take from /n/src, because v8/ and the image differ -- our
		edits since the import, and anything we added.

The middle one needs justifying, because on its face it contradicts "the
repo is the source of truth".  It does not: every file in fromgold.txt has
had its sha256 compared against the repo's copy AT GENERATION TIME, and any
file that differs is moved to fromsrc.txt automatically.  So the repo stays
authoritative and the image is used only as a local cache of bytes we have
already proven we own.

Why it matters: those trees are ~2264 files, and pulling them over netfs
costs a round trip per file through an emulated VAX, an emulated Interlan
and SLiRP.  Measured at roughly 30 files a minute -- 90 minutes.  The same
bytes are already on a disk the machine has mounted, and cpio moves 21 MB
of them in six seconds.  The build refuses to run against a stale list
(`--check', wired into tools/drive-stages48.sh), so the speed costs no
correctness.

THE QUESTION THIS ANSWERS.  Track S builds V8 from our own source, but the
1985 tape is not a complete system: Bell Labs shipped binaries whose sources
they never released.  So "can we stop shipping someone else's disk image?"
reduces to a single checkable claim --

	every byte that exists ONLY on the TUHS image is carried onto ours

-- and everything else is either built from v8/ or already in git.  This
tool computes that set.  It is deliberately generated rather than written by
hand: the moment a source file is recovered, or a command starts building,
the list must shrink, and a hand-written list would not.

THE THREE ORIGINS of a file on the ipnx disk, and how each is decided:

  built    v8/mk/gen/provenance.txt says `build' -- stages 4 to 7 make it
  git      v8/MANIFEST says `source' -- the tape shipped it as text, so
           v8-import.py stored it and `--verify' proves it round-trips.
           Losing the disk image loses nothing.
  carried  THIS FILE.  MANIFEST says `excluded' (machine code, no source),
           or the path is not on the tape at all (built at the Labs, or
           put there by us).  These are unrecoverable if the image goes.

WHAT IS DELIBERATELY NOT CARRIED is as important as what is, so every
exclusion below states its reason.  The rule is: skip only things that are
regenerated by this build, or that are one machine's runtime droppings.
"""

import argparse
import collections
import hashlib
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import v8fs

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, "v8", "mk", "gen", "carry.txt")
GOLDOUT = os.path.join(REPO, "v8", "mk", "gen", "fromgold.txt")
SRCOUT = os.path.join(REPO, "v8", "mk", "gen", "fromsrc.txt")
DIROUT = os.path.join(REPO, "v8", "mk", "gen", "dirs.txt")

# Prefixes we never carry.  Each is either regenerated by stage 8 or is
# state belonging to the machine that happened to write it.
SKIP_PREFIX = [
    ("/dev/", "makedev.sh builds /dev from proto-dev"),
    ("/tmp/", "scratch"),
    ("/usr/tmp/", "scratch"),
    ("/usr/adm/", "one machine's accounting and message log"),
    ("/usr/spool/", "queue state"),
    ("/usr/preserve/", "editor crash recovery"),
    ("/lost+found/", "mklost+found makes it"),
    ("/usr/lost+found/", "mklost+found makes it"),
    # /usr/sys/alice is the Labs' own kernel build directory -- their .s
    # intermediates for the machine called alice.  We DO carry it: it is
    # not on the tape, so retiring the image would destroy the only
    # surviving artefact of Bell Labs' own V8 kernel build.  Listed here
    # only to record that the decision was made rather than overlooked.
]
SKIP_EXACT = {
    "/unix": "stage 7 builds the kernel",
    "/etc/utmp": "who is logged in, on their machine",
    "/etc/mtab": "what was mounted, on their machine",
    "/.profile": "ours -- v8/etc/profile.root",
    "/etc/skel/.profile": "ours -- v8/etc/profile.skel",
    "/usr/jerq/bin/wmux": "ours -- v8/jerq/bin/wmux",
    # builddisk.sh does `cp $SRC/etc/* $MNT/etc', so these two land in /etc
    # as well as at their real destinations. No makefile installs them, so
    # the derived rule below cannot see them.
    "/etc/profile.root": "ours -- v8/etc/profile.root",
    "/etc/profile.skel": "ours -- v8/etc/profile.skel",
}


def load_manifest():
    """image path -> disposition, for every file on the tapes.

    The tape's top level is not the image's: jerq/ and blit/ are installed
    under /usr, everything else keeps its place.  That mapping is the one
    piece of knowledge here that is not in a file somewhere."""
    disp = {}
    for line in open(os.path.join(REPO, "v8", "MANIFEST")):
        if line.startswith("#"):
            continue
        f = line.rstrip("\n").split("\t")
        if len(f) < 5 or f[0] not in ("source", "excluded", "unpacked"):
            continue
        top = f[4].split("/")[0]
        disp["/usr/" + f[4] if top in ("jerq", "blit") else "/" + f[4]] = f[0]
    return disp


def load_destfiles():
    """The exact paths this build installs (mkdep.py's gen/destfiles.txt).

    A file that this build installs AND that is not on the tape at all was
    put there by us, so carrying it off a reference image is wrong twice over:
    the next build regenerates it anyway, and carrying it would freeze
    whatever the last build happened to produce.

    This is the closure condition. Without it, regenerating carry.txt from
    OUR disk instead of the TUHS one adds eight entries -- etc/chroot,
    etc/nmount, the two profiles, the cc -B pass copies lib/as and lib/ld,
    usr/include/ipnx.h and usr/lib/libpen.a -- and the two lists stop
    agreeing, which is exactly the property that says the build no longer
    needs the TUHS disk.

    Derived rather than listed, because a hand-list of "things that are
    ours" is the same trap as the hand-listed copy directories: it is
    correct on the day it is written.
    """
    # These used to live in destdirs.txt, tab-indented, alongside the
    # directories builddisk.sh copies. They do not any more: builddisk.sh
    # word-splits that file into `mkdir', tab and all, so every path in it
    # became an empty directory and the disk would not boot. Separate files
    # now -- see mkdep.py's emit_destfiles().
    p = os.path.join(REPO, "v8", "mk", "gen", "destfiles.txt")
    if not os.path.exists(p):
        return set()
    return {"/" + l.strip() for l in open(p)
            if l.strip() and not l.startswith("#")}


def load_built():
    """The (dir, name) pairs stage 6 installs, so we never carry over one.

    A command can be `excluded' on the tape and `build' for us at the same
    time -- the tape shipped /bin/ls as a binary AND usr/src/cmd/ls.c as
    source.  Ours must win, and the cheapest way to guarantee that is to
    not copy theirs at all."""
    built = set()
    p = os.path.join(REPO, "v8", "mk", "gen", "provenance.txt")
    for line in open(p):
        if line.startswith("#"):
            continue
        f = line.rstrip("\n").split("\t")
        if len(f) >= 3 and f[2] == "build":
            built.add(f[1].rstrip("/") + "/" + f[0])
    return built


def skipped(path):
    for pfx, why in SKIP_PREFIX:
        if path.startswith(pfx):
            return why
    return SKIP_EXACT.get(path)


# The trees stage 8 installs that are neither built nor carried: nroff's
# macros, terminal tables, the manual, the games' data, the 5620's fonts and
# icons.  usr/src, usr/sys and blit are deliberately absent -- they are
# source, they are in git, and a machine that wants them has /n/src.  Their
# binaries are in carry.txt, which is the part that could otherwise be lost.
RUNTIME_TREES = ["/usr/lib/", "/usr/games/", "/usr/man/", "/usr/doc/",
                 "/usr/net/", "/usr/bin/", "/usr/dict/", "/usr/spool/",
                 "/usr/jerq/"]


def split_runtime(image, gold):
    """Split the runtime trees into "identical, take the fast path" and "ours".

    Returns (fromgold text, fromsrc text, ngold, nsrc).

    Every decision here is a sha256 comparison between the image's copy and
    the repo's, so `fromgold' never means "assumed the same" -- it means
    "checked, this run".  A file we have edited since the import moves to
    fromsrc.txt on the next regeneration without anyone noticing it had to.

    fromsrc rows are two columns because the tape's top level and the
    image's disagree: jerq/src/x is served at /n/src/jerq/src/x and belongs
    at /usr/jerq/src/x.  netfsd un-escapes the CASEMAP names, so the
    left-hand column is the true name and never the %4D form."""
    fs = {}
    keep = []
    for line in open(os.path.join(REPO, "v8", "MANIFEST")):
        if line.startswith("#"):
            continue
        f = line.rstrip("\n").split("\t")
        if len(f) < 6 or f[0] != "source":
            continue
        top = f[4].split("/")[0]
        img = "/usr/" + f[4] if top in ("jerq", "blit") else "/" + f[4]
        if any(img.startswith(t) for t in RUNTIME_TREES):
            keep.append((img, f[4], f[5]))

    # One open of the image, two partitions, read on demand.
    readers = {"": v8fs.V8FS(image, "a"),
               "/usr": v8fs.V8FS(image, v8fs.usrpart(image))}
    ingold, insrc = [], []
    for img, tape, stored in sorted(keep):
        rp = os.path.join(REPO, "v8", stored)
        ip = gold.get(img)
        if ip is None or not ip.isreg or not os.path.isfile(rp):
            insrc.append((tape, img.lstrip("/")))
            continue
        r = readers["/usr"] if img.startswith("/usr/") else readers[""]
        sub = img[4:] if img.startswith("/usr/") else img
        inode = r.lookup(sub)
        a = hashlib.sha256(r.read(inode)).hexdigest() if inode else None
        b = hashlib.sha256(open(rp, "rb").read()).hexdigest()
        if a == b:
            ingold.append(img.lstrip("/"))
        else:
            insrc.append((tape, img.lstrip("/")))

    g = ["# Generated by tools/mkcarry.py -- do not edit.",
         "#",
         "# Runtime-tree files whose copy on the reference image is BYTE-",
         "# IDENTICAL to ours in v8/ -- sha256-compared when this file was",
         "# written. Taking them off the mounted image instead of over netfs",
         "# is the difference between six seconds and ninety minutes, and",
         "# costs nothing, because the bytes are the same bytes.",
         "#",
         "# Anything that stops being identical moves to fromsrc.txt by",
         "# itself. Same cpio(1) pass as carry.txt.",
         "#",
         "#\t%d files" % len(ingold), "#"] + ingold
    s = ["# Generated by tools/mkcarry.py -- do not edit.",
         "#",
         "# Runtime-tree files where v8/ and the reference image DIFFER, so",
         "# the repo wins and they come over netfs from /n/src. Our edits",
         "# since the import, and anything we added.",
         "#",
         "# Two columns: source relative to /n/src, destination relative to",
         "# the mount point. They differ because the tape says jerq/ and the",
         "# image says /usr/jerq.",
         "#",
         "#\t%d files" % len(insrc),
         "#",
         "#src\tdst"] + ["%s\t%s" % (a, b) for a, b in insrc]
    return "\n".join(g) + "\n", "\n".join(s) + "\n", len(ingold), len(insrc)


# Trees whose directories we do not reproduce, because we do not install
# their contents either: they are source, they are in git, and a machine that
# wants them has /n/src.
NODIRS = ("/usr/src/", "/usr/sys/", "/usr/blit/")


def emit_dirs(gold, covered):
    """Directories on the reference image that nothing else would create.

    THE OMISSION A FILE LIST CANNOT SEE.  carry.txt, fromgold.txt and the
    DESTDIR copy all create directories as a side effect of putting files in
    them, so every directory with contents appears by itself.  An EMPTY one
    never does -- and the reference image has 29 that matter:
    /usr/spool/uucp with its nine dot-directories, /usr/spool/at/past,
    /usr/spool/locks, /etc/asd/{keys,perm}, /usr/inet/lib,
    /usr/lib/ideal/idfilt, /usr/jerq/demo/src/c, and the /n, /n/home and
    /n/macos mount points, which are ours.

    retire-check.py cannot catch these either: it skips directories, because
    a directory has no content to lose.  True of the bytes, false of the
    system -- uucp will not run without its spool tree and at(1) fails on a
    missing past/.

    SKIP_PREFIX is deliberately NOT applied here, and that is the point of
    having a separate pass.  Those rules say "do not carry one machine's
    queue files", which is right -- and saying the same thing about the
    DIRECTORY throws away structure the system needs: /usr/spool/uucp and
    its nine dot-directories are uucp's working layout, not uucp's backlog.
    Content is state; shape is configuration.

    v8/EMPTYDIRS looks like the obvious source and is the wrong list twice:
    it is in tape paths, and it describes the TAPE rather than a working
    machine, so it carries source directories we deliberately do not install
    and omits everything the Labs made after extracting it.
    """
    want = []
    for path in sorted(gold):
        if not gold[path].isdir or path == "/":
            continue
        if any(path.startswith(t) for t in NODIRS):
            continue
        if path.lstrip("/") in covered:
            continue
        want.append(path.lstrip("/"))
    out = ["# Generated by tools/mkcarry.py -- do not edit.",
           "#",
           "# Directories on the reference image that no file copy would",
           "# create, because they are empty. builddisk.sh mkdirs them.",
           "#",
           "# Sorted parents first, which is load-bearing: V8 has no",
           "# mkdir -p and makes one level at a time.",
           "#",
           "#\t%d directories" % len(want), "#"]
    out += sorted(want, key=lambda d: (d.count("/"), d))
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    # OUR disk, not the TUHS one. Both give the same 1405 paths -- that
    # equality is the whole point of the exercise -- so the default is now
    # the image this build produces and the TUHS one is no longer needed.
    # tools/image-pack.py unpack puts it here.
    ap.add_argument("--image", default=os.path.join(REPO, "work", "myv8", "rp07new"))
    ap.add_argument("--check", action="store_true",
                    help="regenerate and diff against the committed file")
    args = ap.parse_args()

    disp = load_manifest()
    built = load_built()
    destdirs = load_destfiles()

    gold = {}
    for part, pfx in v8fs.wholesystem(args.image):
        fs = v8fs.V8FS(args.image, part)
        for p, ip in fs.walk("/"):
            gold[pfx + p] = ip

    carry, reason = [], {}
    nskip = ncollide = nours = 0
    for path in sorted(gold):
        ip = gold[path]
        if ip.isdir or ip.isdev:
            continue
        if skipped(path):
            nskip += 1
            continue
        if path in built:
            ncollide += 1
            continue
        d = disp.get(path)
        if d == "excluded":
            reason[path] = "no source on the tape"
        elif d is None:
            if path in destdirs:
                nours += 1          # ours, and this build makes it again
                continue
            reason[path] = "not on the tape at all"
        elif d == "unpacked":
            # An ar(1) archive used as a source container.  Its MEMBERS are
            # in git as text, so nothing is lost either way -- but the disk
            # wants the archive, and reassembling one inside V8 is work for
            # no gain.  Carry the file; git keeps the contents readable.
            reason[path] = "ar archive; members are in git"
        else:
            continue			# source -- it is in git
        carry.append(path)

    tree = collections.Counter()
    size = collections.Counter()
    for p in carry:
        k = "/".join(p.split("/")[:3]) if p.count("/") > 2 else os.path.dirname(p) or "/"
        tree[k] += 1
        size[k] += gold[p].size
    total = sum(size.values())

    out = []
    out.append("# Generated by tools/mkcarry.py -- do not edit.")
    out.append("#")
    out.append("# Files that exist ONLY on the TUHS V8 image: machine code the")
    out.append("# tape shipped without source, plus what the Labs (or we) put")
    out.append("# there afterwards. Everything else on that image is either")
    out.append("# built by stages 4-7 or stored as source in v8/ -- so once")
    out.append("# these are on our disk, the TUHS image holds nothing unique")
    out.append("# and can be retired.")
    out.append("#")
    out.append("# builddisk.sh feeds this to cpio(1) in pass mode, from the")
    out.append("# golden image mounted read-only. Bare paths, one per line,")
    out.append("# relative to its root -- so strip comments and pipe it in.")
    out.append("#")
    out.append("#\t%d files\t%d bytes" % (len(carry), total))
    out.append("#\t%d skipped (regenerated here, or one machine's state)" % nskip)
    out.append("#\t%d not carried because we build our own" % ncollide)
    out.append("#\t%d not carried because they are ours and not on the tape" % nours)
    out.append("#")
    out.append("# by tree:")
    for k, v in sorted(tree.items(), key=lambda kv: -size[kv[0]]):
        out.append("#\t%-28s %5d files %10d bytes" % (k, v, size[k]))
    out.append("#")
    for p in carry:
        out.append(p.lstrip("/"))
    text = "\n".join(out) + "\n"

    gtext, stext, ngold, nsrc = split_runtime(args.image, gold)

    # Every directory a file copy will create by itself: the parents of
    # everything in the three lists, plus everything the build installs into
    # (gen/destdirs.txt and gen/destfiles.txt, scraped out of the makefiles).
    covered = set()
    for line in carry:
        p2 = line.lstrip("/")
        while "/" in p2:
            p2 = p2.rsplit("/", 1)[0]
            covered.add(p2)
    for blob in (gtext, stext):
        for line in blob.splitlines():
            if line.startswith("#") or not line.strip():
                continue
            p2 = line.split("\t")[-1]
            while "/" in p2:
                p2 = p2.rsplit("/", 1)[0]
                covered.add(p2)
    for g in ("destdirs.txt", "destfiles.txt"):
        dd = os.path.join(REPO, "v8", "mk", "gen", g)
        if os.path.exists(dd):
            for line in open(dd):
                if not line.startswith("#") and line.strip():
                    covered.add(line.strip())
    dtext = emit_dirs(gold, covered)
    ndirs = sum(1 for l in dtext.splitlines() if not l.startswith("#"))

    if args.check:
        for name, want in ((OUT, text), (GOLDOUT, gtext), (SRCOUT, stext),
                           (DIROUT, dtext)):
            have = open(name).read() if os.path.exists(name) else ""
            if have != want:
                print("%s is STALE -- rerun tools/mkcarry.py"
                      % os.path.basename(name), file=sys.stderr)
                return 1
        print("carry/fromgold/fromsrc/dirs are current (%d/%d/%d files, %d dirs)"
              % (len(carry), ngold, nsrc, ndirs))
        return 0

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write(text)
    open(GOLDOUT, "w").write(gtext)
    open(SRCOUT, "w").write(stext)
    open(DIROUT, "w").write(dtext)
    print("wrote %s: %d files, %d bytes, %d skipped, %d built, %d ours"
          % (os.path.relpath(OUT, REPO), len(carry), total, nskip, ncollide, nours))
    for k, v in sorted(tree.items(), key=lambda kv: -size[kv[0]])[:12]:
        print("   %-28s %5d files %10d" % (k, v, size[k]))
    print("wrote fromgold.txt: %d files identical to ours" % ngold)
    print("wrote fromsrc.txt:  %d files that differ, from /n/src" % nsrc)
    print("wrote dirs.txt:     %d empty directories nothing else creates" % ndirs)
    return 0


if __name__ == "__main__":
    sys.exit(main())
