#!/bin/bash
# Ask the golden image where every command lives, and write v8/mk/where.txt.
#
#	tools/harvest-paths.sh [seconds] [port]
#
# See tools/harvest-paths.exp for why the machine is the authority and the
# source tree is not.  Runs on a COPY of the golden image and nothing inside
# the guest is written; the only output is where.txt on the host.
set -u

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
WORK="$ROOT/work/myv8"
LIMIT=${1:-900}
PORT=${2:-9400}
LOG="$WORK/harvest-paths.log"
OUT="$ROOT/v8/mk/where.txt"

cd "$WORK" || exit 1
export PATH="$ROOT/work/opensimh/BIN:$PATH"

command -v vax780 >/dev/null || { echo "harvest: vax780 not on PATH"; exit 1; }
[[ -e rp06v8.golden ]] || { echo "harvest: no rp06v8.golden"; exit 1; }
[[ -e bootV8 ]] || { echo "harvest: no bootV8"; exit 1; }

# Refuse to run beside another VAX.  Two simulators on one disk image is the
# documented corruption hazard, and this one is cheap to postpone.
if pgrep -x vax780 >/dev/null; then
    echo "harvest: a vax780 is already running -- wait for it"; exit 1
fi

cleanup() {
    [[ -n "${EXP_PID:-}" ]] && kill -9 "$EXP_PID" 2>/dev/null
    pkill -9 -x vax780 2>/dev/null
    true
}
trap cleanup EXIT INT TERM

echo "== copying rp06v8.golden -> harvest.disk =="
rm -f harvest.disk && cp rp06v8.golden harvest.disk

: > "$LOG"
expect "$ROOT/tools/harvest-paths.exp" "$PORT" &
EXP_PID=$!
for ((i = 0; i < LIMIT; i++)); do
    kill -0 "$EXP_PID" 2>/dev/null || break
    sleep 1
done
wait "$EXP_PID" 2>/dev/null
rc=$?

LOGC=$(tr -d '\r' < "$LOG")
if ! grep -q 'HARVEST-DONE-ok' <<< "$LOGC"; then
    echo "harvest: the guest never finished (rc=$rc) -- $LOG"; exit 1
fi

# WHERE lines only, and drop the echo of the command that produces them: the
# tty echoes what we type, so "for f in /bin/*; do echo WHERE $f; done" is
# itself a line containing WHERE.  The echo has a literal '$f' in it and a
# result never does, which is the whole distinction.
{
    echo "# Generated by tools/harvest-paths.sh -- where each command lives on"
    echo "# the shipped image.  The source tree does not say: 164 commands in"
    echo "# usr/src/cmd are loose .c files with no makefile at all, and /bin vs"
    echo "# /usr/bin matters because /usr is a separate filesystem."
    echo "#"
    echo "#	<name>	<directory>"
    grep -o 'WHERE /[^ ]*$' <<< "$LOGC" \
        | grep -v '\$f' \
        | sed 's|^WHERE ||' \
        | awk -F/ '{ n = $NF; d = substr($0, 1, length($0) - length(n) - 1);
                     if (n != "") printf "%s\t%s\n", n, d }' \
        | sort -u
} > "$OUT"

n=$(grep -vc '^#' "$OUT")
echo "harvest: $n entries -> ${OUT#$ROOT/}"
rm -f harvest.disk
